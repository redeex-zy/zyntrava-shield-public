"""Process-level smoke: documented CLI, real TCP API and actual dummy file effects."""

import json
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path


def test_documented_startup_and_authenticated_tcp_journey(tmp_path: Path):
    state = tmp_path / "state"
    init = [sys.executable, "-m", "zyntrava", "init-lab", "--state", str(state)]
    subprocess.run(init, check=True, capture_output=True, timeout=20)  # noqa: S603 -- fixed CLI.
    with socket.socket() as reservation:
        reservation.bind(("127.0.0.1", 0))
        port = reservation.getsockname()[1]
    command = [
        sys.executable,
        "-u",
        "-m",
        "zyntrava",
        "serve",
        "--state",
        str(state),
        "--port",
        str(port),
    ]
    process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)  # noqa: S603 -- fixed CLI, private temp state.
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    base = f"http://127.0.0.1:{port}"

    def request(path, token=None, body=None):
        headers = {} if token is None else {"Authorization": f"Bearer {token}"}
        payload = None
        if body is not None:
            payload = json.dumps(body).encode()
            headers["Content-Type"] = "application/json"
        # base is a fixed numeric-loopback HTTP origin generated above.
        proposed = urllib.request.Request(base + path, data=payload, headers=headers)  # noqa: S310
        with opener.open(proposed, timeout=2) as response:
            return json.load(response)

    try:
        deadline = time.monotonic() + 15
        while True:
            try:
                assert request("/health")["status"] == "ok"
                break
            except urllib.error.URLError:
                if time.monotonic() >= deadline or process.poll() is not None:
                    raise AssertionError("local CLI server did not become healthy") from None
                time.sleep(0.05)
        assert process.stdout is not None
        assert "Synthetic lab API" in process.stdout.readline()
        # Only read credentials generated by this disposable child process; never log them.
        operator = process.stdout.readline().strip().split(": ", 1)[1]
        agent = process.stdout.readline().strip().split(": ", 1)[1]
        session = request("/sessions", agent, {})["session_id"]
        endpoint = f"/sessions/{session}/actions"
        public = request(
            endpoint, agent, {"tool": "read_file", "arguments": {"path": "public/hello.txt"}}
        )
        assert public["execution"] == "succeeded"
        blocked = request(
            endpoint, agent, {"tool": "read_file", "arguments": {"path": "private/forbidden.txt"}}
        )
        assert blocked["status"] == "blocked" and blocked["execution"] == "not_run"
        pending = request(
            endpoint,
            agent,
            {
                "tool": "write_file",
                "arguments": {"path": "reports/tcp.txt", "content": "approved synthetic content"},
            },
        )
        assert pending["status"] == "sent_for_approval"
        approved = request(f"/approvals/{pending['approval_id']}", operator, {"allow": True})
        assert approved["execution"] == "succeeded"
        assert (state / "workspace/reports/tcp.txt").read_text() == "approved synthetic content"
        assert request("/overview", operator)["evaluated_actions"] == 4
    finally:
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=5)
        if process.stdout:
            process.stdout.close()
        if process.stderr:
            process.stderr.close()
