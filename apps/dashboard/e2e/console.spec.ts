import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdirSync, writeFileSync, readdirSync, readFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { resolve } from 'node:path';

test('authenticated console: real enforcement, approval, policy, research and export', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/app/');
  await expect(page.getByRole('heading', { name: 'Intelligence deserves protection.' })).toBeVisible();
  await page.getByLabel('Operator bearer').fill(process.env.ZYNTRAVA_BROWSER_OPERATOR!);
  await page.getByRole('button', { name: 'Connect to local workspace' }).click();
  await expect(page.getByRole('heading', { name: 'Your agent’s security boundary.' })).toBeVisible();
  await page.getByRole('button', { name: 'Research Laboratory', exact: true }).click();
  await page.getByRole('button', { name: 'Run synthetic demonstration' }).click();
  await expect(page.getByText('completed', { exact: true })).toBeVisible({ timeout: 15000 });
  await page.getByRole('button', { name: 'Policies', exact: true }).click();
  await expect(page.getByText('1 pending', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Approve exact action' }).click();
  await expect(page.getByText('No actions waiting for approval.')).toBeVisible();
  await page.getByRole('button', { name: 'Validate and apply policy' }).click();
  await expect(page.getByRole('status')).toHaveText('Validated policy saved');
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(page.getByText('blocked', { exact: true })).toBeVisible();
  mkdirSync(resolve('../../docs/screenshots'), { recursive: true });
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: resolve('../../docs/screenshots/dashboard-overview.png'), fullPage: true });
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
  writeFileSync(resolve('../../artifacts/accessibility-dashboard.json'), JSON.stringify(axe, null, 2));
  expect(axe.violations).toEqual([]);
  await page.getByRole('button', { name: 'Live Activity', exact: true }).click();
  await page.getByLabel('Decision', { exact: true }).selectOption('blocked');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByLabel('Tool', { exact: true }).selectOption('read_file');
  await page.getByLabel('Execution', { exact: true }).selectOption('not_run');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: /Inspect read_file/ }).click();
  await expect(page.getByRole('heading', { name: 'Decision evidence' })).toBeVisible();
  await expect(page.getByText('deny-private-read', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Audit retention (days)').fill('14');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('status')).toContainText('Settings saved');
  await page.getByRole('button', { name: 'Agent Integrations', exact: true }).click();
  await expect(page.getByText('disconnected', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Research Laboratory', exact: true }).click();
  await page.getByLabel('Trace dataset').selectOption('2');
  await page.getByRole('button', { name: 'Run corpus v2', exact: true }).click();
  await expect(page.getByText('completed', { exact: true })).toHaveCount(2, { timeout: 150000 });
  await page.getByRole('button', { name: 'Benchmark Results', exact: true }).click();
  await expect(page.getByRole('cell', { name: '0 / 45', exact: true }).first()).toBeVisible();
  await page.getByLabel('First experiment').selectOption({ index: 1 });
  await page.getByLabel('Second experiment').selectOption({ index: 1 });
  await expect(page.getByText('Choose different experiments.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Research Laboratory', exact: true }).click();
  await page.getByLabel('Trace dataset').selectOption('3');
  await page.getByRole('button', { name: 'Run corpus v3', exact: true }).click();
  await expect(page.getByText('completed', { exact: true })).toHaveCount(3, { timeout: 150000 });
  await page.getByRole('button', { name: 'Benchmark Results', exact: true }).click();
  const executed = page.getByRole('table', { name: /Execution-aware evidence/ }).first();
  await expect(executed).toBeVisible();
  const full = executed.getByRole('row').filter({ has: page.getByRole('rowheader', { name: 'full', exact: true }) });
  await expect(full.getByRole('cell').nth(2)).toHaveText('0');
  await expect(full.getByRole('cell').nth(3)).toHaveText('0');
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export JSON' }).first().click();
  expect((await download).suggestedFilename()).toMatch(/^trace-.*\.json$/);
  await page.getByRole('button', { name: 'Research Laboratory', exact: true }).click();
  await page.getByRole('button', { name: 'Run recovery demonstration', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'Verified in simulator', exact: true })).toBeVisible({ timeout: 15000 });
  await expect(page.getByRole('cell', { name: 'verified', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  const sizing = await page.evaluate(() => ({ width: innerWidth, document: document.documentElement.scrollWidth,
    overflow: [...document.querySelectorAll('body *')].filter(e => e.getBoundingClientRect().right > innerWidth + 1 && getComputedStyle(e).position !== 'fixed').map(e => ({ tag: e.tagName, class: e.className, right: e.getBoundingClientRect().right })).slice(0, 12) }));
  expect(sizing.document, JSON.stringify(sizing)).toBeLessThanOrEqual(sizing.width);
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: resolve('../../docs/screenshots/dashboard-mobile.png'), fullPage: true });
  const samples: number[] = [];
  for (let i=0; i<25; i++) {
    const start = performance.now();
    expect((await page.request.get('/overview', { headers: { Authorization: `Bearer ${process.env.ZYNTRAVA_BROWSER_OPERATOR!}` } })).ok()).toBe(true);
    samples.push(performance.now()-start);
  }
  const assets = resolve('out/_next/static');
  function javascriptBytes(path: string): number { return readdirSync(path,{withFileTypes:true}).reduce((sum,item)=>sum+(item.isDirectory()?javascriptBytes(resolve(path,item.name)):item.name.endsWith('.js')?gzipSync(readFileSync(resolve(path,item.name))).length:0),0); }
  const bytes = javascriptBytes(assets); expect(bytes).toBeLessThan(250*1024);
  const sorted = [...samples].sort((a,b)=>a-b);
  writeFileSync(resolve('../../artifacts/dashboard-performance.json'), JSON.stringify({environment:'Chromium + authenticated loopback API, Windows; no throttling',overviewRoundtripMs:samples,medianMs:sorted[12],p95Ms:sorted[23],allStaticJavaScriptGzipBytes:bytes,budgetBytes:250*1024,limitations:'Whole static bundle sum, not network transfer measurement. No field Core Web Vitals or screen-reader certification.'},null,2));
  await page.route('**/overview', route => route.abort());
  await page.getByRole('button', { name: /Refresh/ }).click();
  await expect(page.getByText('Service unavailable', { exact: true })).toBeVisible();
  await expect(page.getByText('Protection status unknown: service unavailable')).toBeVisible();
  await page.unroute('**/overview');
  await page.getByRole('button', { name: /Refresh/ }).click();
  await expect(page.getByText('● Local service connected', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Disconnect', exact: true }).click();
  await expect(page.getByLabel('Operator bearer')).toHaveValue('');
  expect(errors).toEqual([]);
});
